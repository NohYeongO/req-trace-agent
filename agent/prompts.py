def render_comment_input(query: str, core: str, feedback: str | None) -> str:
    user = f"## 질문\n{query}\n\n## 답변 본문\n{core}\n\n## 코멘트"
    if feedback:
        user = f"## 이전 코멘트가 반려된 이유(반드시 고칠 것)\n{feedback}\n\n" + user
    return user
