def render_status_input(query: str, facts: str, feedback: str | None) -> str:
    user = f"## 질문\n{query}\n\n## 사실\n{facts or '(조회된 사실 없음)'}"
    if feedback:
        user += f"\n\n## 이전 답변이 반려된 이유(반드시 고칠 것)\n{feedback}"
    return user
