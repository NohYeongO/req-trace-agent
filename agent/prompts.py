def render_candidates(candidates: list[dict]) -> str:
    lines = []
    for c in candidates:
        lines.append(f"- {c['id']} {c['name']}: {c.get('description', '')}")
        for cr in c["criteria"]:
            lines.append(f"    · 조건 id={cr['id']}: {cr['text']}")
    return "\n".join(lines) or "(후보 없음)"


